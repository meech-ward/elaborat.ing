import AxeBuilder from "./axe.ts"
import { expect, test, type Page } from "./fixtures.ts"
import { fakeSupabase } from "./fake-supabase.ts"
import { APP_URL } from "./urls.ts"
import { recordFrameMessages } from "./rendered-support.ts"

// Real file input and frame context-menu gestures. The signed-out project
// proves that image bytes and note drafts survive without a server upload.
test.use({ viewport: { width: 1280, height: 900 } })
test.describe.configure({ timeout: 60_000 })
const FRAME = 'iframe[title="Isolated document preview"]:visible'
const frame = (page: Page) => page.frameLocator(FRAME)
const lines = (page: Page) => page.locator(".monaco-editor:visible .view-lines").first()
const png = Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR4nGP4z8DwHwAFAAH/iZk9HQAAAABJRU5ErkJggg==", "base64")
const file = { name: "red.png", mimeType: "image/png", buffer: png }
const NOTE = "# Pictures\n\nAnchor paragraph.\n\nAfter paragraph.\n"

async function openNote(page: Page) {
  await recordFrameMessages(page)
  await fakeSupabase(page)
  await page.goto(APP_URL)
  await page.getByRole("banner").getByRole("link", { name: "Start writing" }).click()
  await expect(page.getByRole("heading", { level: 1, name: "Local project" })).toBeVisible()
  await page.getByRole("button", { name: "New file" }).click()
  await page.getByRole("menuitem", { name: "New note", exact: true }).click()
  await page.getByRole("textbox", { name: /^Name of the new note in / }).fill("pictures.mdx")
  await page.keyboard.press("Enter")
  await expect(lines(page)).toBeVisible()
  await lines(page).click()
  await page.keyboard.type(NOTE)
  await page.getByRole("button", { name: "Save", exact: true }).click()
  await expect(page.getByRole("tab", { name: "pictures.mdx", exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Rendered", exact: true }).click()
  await expect(frame(page).getByText("Anchor paragraph.", { exact: true })).toBeVisible()
}

async function picker(page: Page) {
  await frame(page).getByText("Anchor paragraph.", { exact: true }).click({ button: "right" })
  await frame(page).getByRole("menu", { name: "Insert block" }).getByRole("menuitem", { name: "Image", exact: true }).click()
  const dialog = page.getByRole("dialog", { name: "Insert image", exact: true })
  await expect(dialog).toBeVisible()
  return dialog
}

async function upload(page: Page, alt: string) {
  const dialog = await picker(page)
  await dialog.getByLabel("Upload images", { exact: true }).setInputFiles(file)
  await expect(dialog.getByLabel("Image description", { exact: true })).toBeEnabled()
  await dialog.getByLabel("Image description", { exact: true }).fill(alt)
  await dialog.getByRole("button", { name: "Insert image", exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(frame(page).getByRole("img", { name: alt, exact: true })).toBeVisible()
}

test("upload inserts a portable reference, Undo and Redo work, and Save and reload keep the pixels", async ({ page }) => {
  await openNote(page)
  await upload(page, "A red pixel")
  const image = frame(page).getByRole("img", { name: "A red pixel", exact: true })
  await expect(image).toHaveAttribute("src", /^data:image\/(png|webp);base64,/)
  await frame(page).getByText("After paragraph.", { exact: true }).click()
  await page.keyboard.press("ControlOrMeta+z")
  await expect(image).toHaveCount(0)
  await page.keyboard.press("ControlOrMeta+Shift+z")
  await expect(image).toBeVisible()
  await page.getByRole("button", { name: "Save", exact: true }).click()
  await expect(page.getByRole("tab", { name: "pictures.mdx", exact: true })).toBeVisible()
  await page.reload()
  await expect(image).toBeVisible({ timeout: 15_000 })
  await page.getByRole("button", { name: "Source", exact: true }).click()
  await expect(lines(page)).toContainText("![A red pixel](")
  await expect(lines(page)).not.toContainText("data:image")
  await expect(lines(page)).toContainText("Anchor paragraph.")
  await expect(lines(page)).toContainText("After paragraph.")
})

test("Cancel keeps the note unchanged and a saved project image can be reused with separate alt text", async ({ page }) => {
  await openNote(page)
  const cancelled = await picker(page)
  await cancelled.getByLabel("Upload images", { exact: true }).setInputFiles(file)
  await expect(cancelled.getByLabel("Image description", { exact: true })).toBeEnabled()
  await cancelled.getByRole("button", { name: "Cancel", exact: true }).click()
  await expect(frame(page).locator("img")).toHaveCount(0)
  await upload(page, "First description")
  await frame(page).getByText("After paragraph.", { exact: true }).click()
  await page.getByRole("button", { name: "Save", exact: true }).click()
  await page.reload()
  await expect(frame(page).getByRole("img", { name: "First description", exact: true })).toBeVisible({ timeout: 15_000 })
  const dialog = await picker(page)
  const existing = dialog.getByLabel("Choose from project", { exact: true })
  const path = await existing.locator("option").last().getAttribute("value")
  expect(path).toMatch(/\.png$/)
  await existing.selectOption(path!)
  await dialog.getByLabel("Image description", { exact: true }).fill("Second description")
  await dialog.getByRole("button", { name: "Insert image", exact: true }).click()
  await expect(frame(page).getByRole("img", { name: "First description", exact: true })).toBeVisible()
  await expect(frame(page).getByRole("img", { name: "Second description", exact: true })).toBeVisible()
  await expect(page.getByText(/^Edit not applied:/)).toHaveCount(0)
})

test("the image picker is accessible on a phone and Decorative produces an empty alt", async ({ page }) => {
  await openNote(page)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole("navigation", { name: "Workspace files" }).getByRole("button", { name: "pictures.mdx", exact: true }).click()
  const dialog = await picker(page)
  await dialog.getByLabel("Upload images", { exact: true }).setInputFiles(file)
  const decorative = dialog.getByRole("checkbox", { name: "Decorative image", exact: true })
  await expect(decorative).toBeEnabled()
  await decorative.check()
  await expect(dialog.getByLabel("Image description", { exact: true })).toBeDisabled()
  const results = await new AxeBuilder({ page }).include('[role="dialog"]').analyze()
  expect(results.violations.map((violation) => ({ id: violation.id, nodes: violation.nodes.map((node) => node.target) }))).toEqual([])
  await dialog.getByRole("button", { name: "Insert image", exact: true }).click()
  await expect(frame(page).getByRole('button', { name: 'View image', exact: true }).locator('img')).toBeVisible()
})


test("resize makes a new asset, retains the original, and writes a Markdown caption", async ({ page }) => {
  await openNote(page)
  const dialog = await picker(page)
  await dialog.getByLabel("Upload images", { exact: true }).setInputFiles(file)
  await expect(dialog.getByLabel("Image description", { exact: true })).toBeEnabled()
  await dialog.getByText("Resize or crop a copy", { exact: true }).click()
  await dialog.getByLabel("Output width", { exact: true }).fill("20")
  await expect(dialog.getByLabel("Output height", { exact: true })).toHaveValue("20")
  await dialog.getByRole("button", { name: "Apply resize and crop", exact: true }).click()
  await expect(dialog.getByText(/20 × 20/)).toBeVisible()
  await dialog.getByLabel("Image description", { exact: true }).fill("A larger red pixel")
  await dialog.getByLabel("Caption (Markdown)", { exact: true }).fill("A **red** pixel with a [caption](https://example.com).")
  await dialog.getByRole("button", { name: "Insert image", exact: true }).click()
  await expect(frame(page).getByRole("img", { name: "A larger red pixel", exact: true })).toBeVisible()
  await expect(frame(page).locator("strong").filter({ hasText: "red" })).toBeVisible()
  await page.getByRole("button", { name: "Save", exact: true }).click()
  const again = await picker(page)
  await expect(again.getByLabel("Choose from project", { exact: true }).locator("option")).toHaveCount(3)
  await again.getByRole("button", { name: "Cancel", exact: true }).click()
  await page.getByRole("button", { name: "Source", exact: true }).click()
  await expect(lines(page)).toContainText("**red**")
  await expect(lines(page)).not.toContainText("data:image")
})

test("rendered image controls edit the description and rich caption, remove the figure, and Undo restores it", async ({ page }) => {
  await openNote(page)
  await upload(page, "Original description")
  await frame(page).getByRole("button", { name: "Edit description", exact: true }).click()
  const description = frame(page).getByRole("dialog", { name: "Image description", exact: true })
  await description.getByLabel("Image description", { exact: true }).fill("Updated description")
  await description.getByRole("button", { name: "Apply description", exact: true }).click()
  const image = frame(page).getByRole("img", { name: "Updated description", exact: true })
  await expect(image).toBeVisible()
  await frame(page).getByRole("button", { name: "Edit caption", exact: true }).click()
  const caption = frame(page).getByRole("dialog", { name: "Image caption", exact: true })
  await caption.getByLabel("Caption (Markdown)", { exact: true }).fill("A **rich** caption with a [link](https://example.com).")
  await caption.getByRole("button", { name: "Apply caption", exact: true }).click()
  const figure = frame(page).locator("figure")
  await expect(figure.getByRole("img", { name: "Updated description", exact: true })).toBeVisible()
  await expect(figure.locator("figcaption strong")).toHaveText("rich")
  await expect(figure.getByRole("link", { name: "link", exact: true })).toHaveAttribute("href", "https://example.com")
  await figure.getByRole("button", { name: "Remove image", exact: true }).click()
  await expect(frame(page).locator("figure")).toHaveCount(0)
  await expect(image).toHaveCount(0)
  await frame(page).getByText("After paragraph.", { exact: true }).click()
  await page.keyboard.press("ControlOrMeta+z")
  await expect(image).toBeVisible()
  await expect(figure.locator("figcaption strong")).toHaveText("rich")
  await expect(page.getByText(/^Edit not applied:/)).toHaveCount(0)
  await page.getByRole("button", { name: "Source", exact: true }).click()
  await expect(lines(page)).toContainText("![Updated description](")
  await expect(lines(page)).toContainText("A **rich** caption")
  await expect(lines(page)).toContainText("Anchor paragraph.")
  await expect(lines(page)).toContainText("After paragraph.")
})

test("an animated project image starts paused for reduced motion and Play and Pause switch actual bytes", async ({ page }) => {
  await openNote(page)
  const dialog = await picker(page)
  const gif = Buffer.from("R0lGODlhAgACAIEAAP8AAAAAAAAAAAAAACH/C05FVFNDQVBFMi4wAwEAAAAh+QQAFAAAACwAAAAAAgACAAAIBgABCAQQEAAh+QQBFAABACwAAAAAAgACAIEAAP8AAAAAAAAAAAAIBgABCAQQEAA7", "base64")
  await dialog.getByLabel("Upload images", { exact: true }).setInputFiles({ name: "animated.gif", mimeType: "image/gif", buffer: gif })
  await expect(dialog.getByLabel("Image description", { exact: true })).toBeEnabled()
  await dialog.getByLabel("Image description", { exact: true }).fill("Red and blue animation")
  await dialog.getByRole("button", { name: "Insert image", exact: true }).click()
  await expect(dialog).toBeHidden()
  await page.getByRole("button", { name: "Save", exact: true }).click()
  await page.getByRole("button", { name: "Source", exact: true }).click()
  const reference = /\]\(([^)]+\.gif)\)/.exec((await lines(page).textContent()) ?? "")?.[1]
  expect(reference).toBeTruthy()
  const location = new URL(page.url())
  location.pathname = `${location.pathname.slice(0, location.pathname.lastIndexOf("/") + 1)}${reference}`
  await page.emulateMedia({ reducedMotion: "reduce" })
  await page.goto(location.href)
  const play = page.getByRole("button", { name: "Play animation", exact: true })
  await expect(play).toHaveAttribute("aria-pressed", "false")
  const image = page.getByRole("img", { name: "animated.gif", exact: true })
  const mediaType = () => image.evaluate(async (element) => (await (await fetch((element as HTMLImageElement).src)).blob()).type)
  expect(await mediaType()).not.toBe("image/gif")
  await play.click()
  await expect(page.getByRole("button", { name: "Pause animation", exact: true })).toHaveAttribute("aria-pressed", "true")
  expect(await mediaType()).toBe("image/gif")
  await page.getByRole("button", { name: "Pause animation", exact: true }).click()
  await expect(play).toHaveAttribute("aria-pressed", "false")
  expect(await mediaType()).not.toBe("image/gif")
})
