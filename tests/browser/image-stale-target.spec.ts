import { expect, test } from "./fixtures.ts"
import { fakeSupabase } from "./fake-supabase.ts"
import { APP_URL } from "./urls.ts"

const png = Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR4nGP4z8DwHwAFAAH/iZk9HQAAAABJRU5ErkJggg==", "base64")
test.use({ viewport: { width: 1280, height: 900 } })
test.describe.configure({ timeout: 60_000 })

test("changing the active note while the picker is open refuses the stale insertion and rolls back its staged image", async ({ page, appErrors }) => {
  appErrors.expect("The note changed while choosing an image")
  appErrors.expect("The document changed while choosing images")
  await fakeSupabase(page)
  await page.goto(APP_URL)
  await page.getByRole("banner").getByRole("link", { name: "Start writing" }).click()
  await expect(page.getByRole("tab", { name: "welcome.mdx", exact: true })).toBeVisible()
  await page.getByRole("button", { name: "New file", exact: true }).click()
  await page.getByRole("menuitem", { name: "New note", exact: true }).click()
  await page.getByRole("textbox", { name: /^Name of the new note in / }).fill("stale.mdx")
  await page.keyboard.press("Enter")
  const source = page.locator(".monaco-editor:visible .view-lines").first()
  await expect(source).toBeVisible()
  await source.click()
  await page.keyboard.type("Anchor paragraph.\n")
  await page.getByRole("button", { name: "Save", exact: true }).click()
  await expect(page.getByRole("tab", { name: "stale.mdx", exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Rendered", exact: true }).click()
  const frame = page.frameLocator('iframe[title="Isolated document preview"]:visible')
  await frame.getByText("Anchor paragraph.", { exact: true }).click({ button: "right" })
  await frame.getByRole("menuitem", { name: "Image", exact: true }).click()
  const picker = page.getByRole("dialog", { name: "Insert image", exact: true })
  await picker.getByLabel("Upload images", { exact: true }).setInputFiles({ name: "stale.png", mimeType: "image/png", buffer: png })
  await expect(picker.getByLabel("Image description", { exact: true })).toBeEnabled()
  await picker.getByLabel("Image description", { exact: true }).fill("Must not be inserted")
  // Browser navigation can change a tab even while the modal traps page focus.
  await page.goBack()
  await expect(page.getByRole("tab", { name: "welcome.mdx", exact: true, includeHidden: true })).toHaveAttribute("aria-selected", "true")
  await picker.getByRole("button", { name: "Insert image", exact: true }).click()
  await expect(picker.getByRole("alert")).toContainText("The document changed while choosing images")
  await picker.getByRole("button", { name: "Cancel", exact: true }).click()
  await page.getByRole("tab", { name: "stale.mdx", exact: true }).click()
  await page.getByRole("button", { name: "Source", exact: true }).click()
  await expect(source).toContainText("Anchor paragraph.")
  await expect(source).not.toContainText("![")
  await expect(page.getByRole("button", { name: "Actions for images/stale.png", exact: true })).toHaveCount(0)
})
