test("a background refresh keeps the category name focused while typing", async ({ page }) => {
  await fakeSupabase(page)
  await signedIn(page)
  await home(page)
  await page.getByRole("button", { name: "New category", exact: true }).click()
  const dialog = page.getByRole("dialog", { name: "New category", exact: true })
  const name = dialog.getByLabel("Category name", { exact: true })
  await name.fill("Video")
  let release: (() => void) | undefined
  const held = new Promise<void>(resolve => { release = resolve })
  let requested = false
  await page.route("**/rest/v1/rpc/list_project_categories", async route => {
    requested = true
    await held
    await route.fallback()
  })
  try {
    await page.evaluate(() => window.dispatchEvent(new Event("focus")))
    await expect.poll(() => requested).toBe(true)
    await expect(name).toBeEnabled()
    await expect(name).toBeFocused()
    await name.pressSequentially(" scripts")
    await expect(name).toHaveValue("Video scripts")
    await expect(name).toBeFocused()
  } finally { release?.() }
  await dialog.getByRole("button", { name: "Create category", exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByRole("link", { name: "Video scripts", exact: true })).toBeVisible()
})

