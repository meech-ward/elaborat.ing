test("a viewer organizes a shared project into multiple personal categories and can remove one", async ({ page }) => {
  const fake = await fakeSupabase(page)
  await project(fake, "Alpha")
  const viewed = await project(fake, "Viewed", OTHER)
  fake.server.share(viewed, person.id, "viewer")
  const videos = category(fake, "Videos")
  const research = category(fake, "Research")
  await signedIn(page)
  await home(page, "all")
  await page.getByRole("button", { name: "Actions for Viewed", exact: true }).click()
  await page.getByRole("menuitem", { name: "Categories…", exact: true }).click()
  const choices = page.getByRole("dialog", { name: "Categories for Viewed", exact: true })
  await choices.getByRole("checkbox", { name: "Videos", exact: true }).check()
  await choices.getByRole("checkbox", { name: "Research", exact: true }).check()
  await choices.getByRole("button", { name: "Save categories", exact: true }).click()
  await expect(choices).toBeHidden()
  expect(fake.categories.categories.get(videos)?.projects.has(viewed)).toBe(true)
  expect(fake.categories.categories.get(research)?.projects.has(viewed)).toBe(true)
  expect(fake.server.role(person.id, fake.server.projects.get(viewed)!)).toBe("viewer")
  await page.getByRole("link", { name: "Back to categories", exact: true }).click()
  await page.getByRole("link", { name: "Videos", exact: true }).click()
  await expect(page.getByRole("link", { name: "Viewed", exact: true })).toBeVisible()
  await expect(page.getByRole("link", { name: "Alpha", exact: true })).toHaveCount(0)
  await page.getByRole("button", { name: "Actions for Viewed", exact: true }).click()
  await page.getByRole("menuitem", { name: "Categories…", exact: true }).click()
  await choices.getByRole("checkbox", { name: "Videos", exact: true }).uncheck()
  await choices.getByRole("button", { name: "Save categories", exact: true }).click()
  await expect(choices).toBeHidden()
  await expect(page.getByRole("link", { name: "Viewed", exact: true })).toHaveCount(0)
  expect(fake.categories.categories.get(videos)?.projects.has(viewed)).toBe(false)
  expect(fake.categories.categories.get(research)?.projects.has(viewed)).toBe(true)
  await page.getByRole("link", { name: "Back to categories", exact: true }).click()
  await page.getByRole("link", { name: "Uncategorized", exact: true }).click()
  await expect(page.getByRole("link", { name: "Alpha", exact: true })).toBeVisible()
  await expect(page.getByRole("link", { name: "Viewed", exact: true })).toHaveCount(0)
})

test("archive and restore a category preserves projects and filters the archived project section", async ({ page }) => {
  const fake = await fakeSupabase(page)
  const alpha = await project(fake, "Alpha")
  const old = await project(fake, "Old")
  const elsewhere = await project(fake, "Elsewhere")
  await fake.server.remote(person.id).archiveProject(old)
  const videos = category(fake, "Videos", [alpha, old])
  category(fake, "Research", [elsewhere])
  await signedIn(page)
  await home(page, videos)
  await expect(page.getByRole("link", { name: "Alpha", exact: true })).toBeVisible()
  await expect(page.getByRole("region", { name: "Archived", exact: true }).getByRole("link", { name: "Old", exact: true })).toBeVisible()
  await expect(page.getByRole("link", { name: "Elsewhere", exact: true })).toHaveCount(0)
  await categoryAction(page, "Videos", "Archive category")
  const archive = page.getByRole("dialog", { name: "Archive Videos", exact: true })
  await expect(archive).toContainText("Its projects and their sharing stay as they are.")
  await archive.getByRole("button", { name: "Archive category", exact: true }).click()
  await expect(archive).toBeHidden()
  await page.getByRole("link", { name: "Back to categories", exact: true }).click()
  await expect(page.getByRole("link", { name: "Videos", exact: true })).toHaveCount(0)
  await page.getByRole("button", { name: "Archived categories", exact: true }).click()
  const archived = page.getByRole("dialog", { name: "Archived categories", exact: true })
  // An archived name can be changed before restoring it, including after a name collision.
  await archived.getByRole("button", { name: "Rename archived category Videos", exact: true }).click()
  const rename = page.getByRole("dialog", { name: "Rename Videos", exact: true })
  await rename.getByLabel("Category name", { exact: true }).fill("Video scripts")
  await rename.getByRole("button", { name: "Save name", exact: true }).click()
  await expect(rename).toBeHidden()
  await archived.getByRole("button", { name: "Restore Video scripts", exact: true }).click()
  await expect(archived).toContainText("No archived categories.")
  await archived.getByRole("button", { name: "Close", exact: true }).click()
  await expect(categoryCard(page, "Video scripts")).toContainText("2 projects")
  expect(fake.categories.categories.get(videos)?.projects).toEqual(new Set([alpha, old]))
  expect(fake.server.projects.has(alpha)).toBe(true)
  expect(fake.server.projects.get(old)?.archivedAt).not.toBeNull()
})

