test.describe.configure({ timeout: 60_000 })

const OTHER = "5d6e7f80-9a1b-4c2d-8e3f-4a5b6c7d8e9f"
const projectHref = (id: string) => new URL(`projects/${id}`, APP_URL).href

async function project(fake: FakeSupabase, title: string, owner = person.id) {
  const id = crypto.randomUUID()
  await fake.server.remote(owner).createProject(id, title)
  await fake.server.remote(owner).saveFiles(id, crypto.randomUUID(), [{ op: "put", path: "readme.md", content: `# ${title}\n` }])
  return id
}

function category(fake: FakeSupabase, name: string, projects: string[] = []) {
  const id = crypto.randomUUID()
  fake.categories.call(person.id, "create_project_category", { category_id: id, name })
  for (const projectId of projects) fake.categories.call(person.id, "set_project_category_membership", { category_id: id, project_id: projectId, included: true })
  return id
}

async function home(page: Page, selection?: string) {
  await page.goto(new URL(selection ? `?category=${encodeURIComponent(selection)}` : "", APP_URL).href)
  await expect(page.getByRole("heading", { name: "Your projects", exact: true })).toBeVisible()
  await expect(page.getByRole("button", { name: "New category", exact: true })).toBeEnabled()
}

const categoryCard = (page: Page, name: string) => page.getByRole("listitem").filter({ has: page.getByRole("link", { name, exact: true }) })

async function categoryAction(page: Page, name: string, action: string) {
  await page.getByRole("button", { name: `Actions for category ${name}`, exact: true }).click()
  await page.getByRole("menuitem", { name: action, exact: true }).click()
}

