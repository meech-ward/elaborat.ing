import { createHash } from 'node:crypto'
import { mkdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { build, type Plugin } from 'vite'
import { d2Engine } from './d2-engine.ts'
import { excalidrawSubsetWorker } from './excalidraw-subset-worker.ts'
import { nativeFontAssets } from './native-font-assets.ts'

const REPO = path.resolve(import.meta.dirname, '..')
type Output = { output: Array<{ type: 'chunk'; fileName: string; code: string } | { type: 'asset'; fileName: string; source: string | Uint8Array }> }

/** Separate server-requested renderer, absent from ordinary app imports/precache. */
export async function buildAgentPreview(outDir: string): Promise<void> {
  const result = await build({
    configFile: false,
    root: path.join(REPO, 'src/agent-preview'),
    base: './',
    publicDir: false,
    mode: 'production',
    logLevel: 'warn',
    define: { 'process.env.NODE_ENV': JSON.stringify('production') },
    resolve: { alias: { '@': path.join(REPO, 'src') } },
    plugins: [nativeFontAssets(), excalidrawSubsetWorker(), d2Engine()],
    worker: { format: 'es' },
    build: {
      write: false,
      minify: true,
      license: { fileName: 'third-party-notices.txt' },
      rolldownOptions: {
        input: {
          index: path.join(REPO, 'src/agent-preview/index.html'),
          // A real entry keeps Rolldown's shared CJS helpers in a DOM-free
          // runtime chunk. As only a dynamic import, the native worker could
          // otherwise import those helpers from the renderer and its preload code.
          'native-subset-worker': path.join(REPO, 'node_modules/@excalidraw/excalidraw/dist/prod/subset-worker.chunk.js'),
        },
        preserveEntrySignatures: 'strict',
        output: { codeSplitting: { groups: [
          { name: 'preload-helper', test: /^\0vite\/preload-helper/, priority: 100 },
          { name: 'preview-protocol', test: /[\\/]agent-preview[\\/]protocol\.ts$/, priority: 80 },
          { name: 'drawing-assets', test: /[\\/]drawings[\\/]assets\.ts$/, priority: 80 },
        ] } },
      },
    },
  }) as Output | Output[]
  const files = new Map<string, Uint8Array>()
  for (const item of (Array.isArray(result) ? result : [result]).flatMap(entry => entry.output)) {
    const content = item.type === 'chunk' ? item.code : item.source
    files.set(item.fileName, typeof content === 'string' ? new TextEncoder().encode(content) : content)
  }
  if (!files.has('index.html')) throw new Error('The agent renderer did not produce its entry page.')
  const digest = createHash('sha256')
  for (const name of [...files.keys()].sort()) digest.update(name).update('\0').update(files.get(name)!).update('\0')
  const id = digest.digest('hex').slice(0, 16)
  const folder = `agent-preview/${id}/`
  for (const [name, bytes] of files) {
    const filename = path.join(outDir, folder, name)
    mkdirSync(path.dirname(filename), { recursive: true })
    writeFileSync(filename, bytes)
  }
  const entries = [...files.keys()].sort()
  const assets = entries.map(name => `/${folder}${name}`)
  writeFileSync(path.join(outDir, folder, 'manifest.json'), `${JSON.stringify({ build: id, entry: `/${folder}index.html`, assets })}\n`)
  writeFileSync(path.join(outDir, 'agent-preview/versions.json'), `${JSON.stringify({ versions: [{ folder, files: [...entries, 'manifest.json'] }] })}\n`)
  const manifest = `// Generated by vite-plugins/agent-preview.ts. Run bun run build to refresh.\n` +
    `export const PREVIEW_BUILD = ${JSON.stringify(id)}\n` +
    `export const PREVIEW_ENTRY = ${JSON.stringify(`/${folder}index.html`)}\n` +
    `export const PREVIEW_ASSETS: string[] = ${JSON.stringify(assets, null, 2)}\n`
  writeFileSync(path.join(REPO, 'supabase/functions/mcp-server/tools/previewManifest.ts'), manifest)
}

export function agentPreview(): Plugin {
  let outDir: string
  let enabled = false
  return {
    name: 'agent-preview',
    apply: 'build',
    configResolved(config) {
      outDir = path.resolve(config.root, config.build.outDir)
      enabled = !config.isWorker
    },
    async closeBundle() {
      if (enabled) await buildAgentPreview(outDir)
    },
  }
}
